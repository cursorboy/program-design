/** Map a FlowStep kind to its glossary concept key. */
export function conceptKeyForStep(kind: string): string | null {
  switch (kind) {
    case 'page':
      return 'page';
    case 'action':
      return 'order-ticket';
    case 'endpoint':
      return 'endpoint';
    case 'guard':
      return 'guard';
    case 'table':
      return 'records';
    default:
      return null;
  }
}
