/**
 * glossary.ts — the teaching layer for progressive disclosure.
 *
 * One consistent RESTAURANT analogy runs through every entry (see docs/learn.md):
 *   front counter = the pages people see · kitchen = the working back end ·
 *   doors = endpoints · security guard = middleware · filing cabinets = database
 *   tables · recipe book = schema · pantry suppliers = dependencies · sticky
 *   notes with door codes = environment variables · order tickets = requests.
 *
 * Each concept gives a non-coder a friendly name, the real technical word, a
 * two-sentence plain definition, a one-sentence "why a builder should care", and
 * the shared analogy. The app renders these in the learn popover and the
 * "Learn more" panel; nothing here is generated by an LLM.
 */
export interface Concept {
  key: string;
  /** Friendly, non-technical name. */
  friendly: string;
  /** The real technical term. */
  technical: string;
  /** ≤ 2 sentences, plain English. */
  plain: string;
  /** One sentence: why a builder should care. */
  why: string;
  /** The restaurant analogy for this concept. */
  analogy: string;
}

